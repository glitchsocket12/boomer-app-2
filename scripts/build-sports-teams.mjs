// Regenerates supabase/functions/_shared/sportsTeams.generated.ts from ESPN's public team lists.
//
// Run by hand (`node scripts/build-sports-teams.mjs`) when leagues change — realignment, a new
// expansion team, a rename. That's a once-a-year event at most, which is the whole point: the
// event-enrichment feature does its "is this a sports game?" detection against this static file,
// so the common path costs zero network calls and zero AI tokens.
//
// ESPN's team JSON names its fields inconsistently between pro and college:
//   pro     -> displayName "Arizona Diamondbacks", name "Diamondbacks", location "Arizona"
//   college -> displayName "Abilene Christian Wildcats", name "Wildcats", location "Abilene Christian"
// `name` is reliably the mascot in both, and `location` reliably the city/school, so those are what
// we keep. `shortDisplayName` is NOT consistent (it's the mascot for pro, the school for college)
// and `abbreviation` is far too collision-prone to match on, so both are dropped.

import { writeFile } from 'node:fs/promises'

const LEAGUES = {
  mlb: { path: 'baseball/mlb', label: 'MLB', pro: true },
  nfl: { path: 'football/nfl', label: 'NFL', pro: true },
  nba: { path: 'basketball/nba', label: 'NBA', pro: true },
  wnba: { path: 'basketball/wnba', label: 'WNBA', pro: true },
  nhl: { path: 'hockey/nhl', label: 'NHL', pro: true },
  mls: { path: 'soccer/usa.1', label: 'MLS', pro: true },
  ncaaf: { path: 'football/college-football', label: 'College Football', pro: false },
  ncaam: { path: 'basketball/mens-college-basketball', label: "Men's College Basketball", pro: false },
  ncaaw: { path: 'basketball/womens-college-basketball', label: "Women's College Basketball", pro: false },
}

// Bare-location matching ("we went to the LSU game") is useful for schools but catastrophic for
// plain place names — "Denver" and "Colorado" appear in half the events in a Denver-based user's
// account and none of them are games. Every pro team's location is by definition one of those
// plain place names, so the denylist is derived from the pro roster itself rather than hardcoded,
// plus the state names, which are locations for several college teams but never a game signal.
const US_STATES = [
  'alabama', 'alaska', 'arizona', 'arkansas', 'california', 'colorado', 'connecticut', 'delaware',
  'florida', 'georgia', 'hawaii', 'idaho', 'illinois', 'indiana', 'iowa', 'kansas', 'kentucky',
  'louisiana', 'maine', 'maryland', 'massachusetts', 'michigan', 'minnesota', 'mississippi',
  'missouri', 'montana', 'nebraska', 'nevada', 'new hampshire', 'new jersey', 'new mexico',
  'new york', 'north carolina', 'north dakota', 'ohio', 'oklahoma', 'oregon', 'pennsylvania',
  'rhode island', 'south carolina', 'south dakota', 'tennessee', 'texas', 'utah', 'vermont',
  'virginia', 'washington', 'west virginia', 'wisconsin', 'wyoming',
]

async function fetchLeague(id, path) {
  const res = await fetch(`https://site.api.espn.com/apis/site/v2/sports/${path}/teams?limit=1000`)
  if (!res.ok) throw new Error(`${id}: HTTP ${res.status}`)
  const json = await res.json()
  const raw = json.sports?.[0]?.leagues?.[0]?.teams ?? []
  return raw
    .map((x) => x.team)
    .filter((t) => t?.id && t?.displayName && t?.name && t?.location)
    .map((t) => ({
      id: String(t.id),
      league: id,
      name: t.displayName.trim(),
      mascot: t.name.trim(),
      location: t.location.trim(),
    }))
}

const teams = []
for (const [id, cfg] of Object.entries(LEAGUES)) {
  const got = await fetchLeague(id, cfg.path)
  console.log(`${id.padEnd(6)} ${String(got.length).padStart(4)} teams`)
  teams.push(...got)
}

// Stable ordering so a regeneration produces a clean diff instead of a reshuffled 1,500-line file.
teams.sort((a, b) => a.league.localeCompare(b.league) || a.id.localeCompare(b.id))

const generic = new Set(US_STATES)
for (const t of teams) {
  // MLS is the odd one out: ESPN puts the full club name in displayName, name AND location, so
  // "Colorado Rapids" is its own location. Adding that to the denylist would be pointless (nobody
  // writes "Colorado Rapids" meaning a place) and would block a legitimate full-name match, so
  // only genuine city components — where location is a proper substring of the full name — count.
  if (LEAGUES[t.league].pro && t.location !== t.name) generic.add(t.location.toLowerCase())
}

const header = `// AUTO-GENERATED by scripts/build-sports-teams.mjs on ${new Date().toISOString().slice(0, 10)}.
// Do not edit by hand — re-run the script instead. See that file for why these fields and not others.
`

const body = `${header}
export type LeagueId = ${Object.keys(LEAGUES).map((k) => `'${k}'`).join(' | ')}

export type SportsTeam = {
  id: string
  league: LeagueId
  /** Full name as ESPN renders it, e.g. "Colorado Rockies" / "Abilene Christian Wildcats". */
  name: string
  /** Mascot only, e.g. "Rockies" / "Wildcats". */
  mascot: string
  /** City or school only, e.g. "Colorado" / "Abilene Christian". */
  location: string
}

export const LEAGUES: Record<LeagueId, { path: string; label: string; pro: boolean }> = ${JSON.stringify(
  Object.fromEntries(Object.entries(LEAGUES).map(([k, v]) => [k, { path: v.path, label: v.label, pro: v.pro }])),
  null,
  2,
)}

/**
 * Locations too generic to treat as a game signal on their own — every pro team's city, plus the
 * US states. "Denver" is where a user lives; "Gonzaga" is only ever a school.
 */
export const GENERIC_LOCATIONS: ReadonlySet<string> = new Set(${JSON.stringify([...generic].sort(), null, 2)})

/**
 * Parsed from a string rather than written as a TS array literal: at ~1,650 entries the literal
 * form makes tsc give up with "union type that is too complex to represent" (TS2590), which fails
 * \`deno check\` for the whole project. Parsing costs a couple of milliseconds once per isolate and
 * type-safety is unaffected — the data is generated, not hand-written.
 */
export const SPORTS_TEAMS: readonly SportsTeam[] = JSON.parse(${JSON.stringify(JSON.stringify(teams))})
`

const out = new URL('../supabase/functions/_shared/sportsTeams.generated.ts', import.meta.url)
await writeFile(out, body)
console.log(`\nwrote ${teams.length} teams + ${generic.size} generic locations`)
